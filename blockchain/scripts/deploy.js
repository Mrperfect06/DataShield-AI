/**
 * DataShield AI — Contract Deployment Script
 *
 * Deploys the DataShieldAudit contract, then persists the deployed address
 * and ABI to JSON files so the Python client can pick them up at runtime.
 *
 * Usage:
 *   npx hardhat run scripts/deploy.js --network localhost
 *   npx hardhat run scripts/deploy.js --network polygon_amoy
 */

const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await hre.ethers.getSigners();
  console.log("───────────────────────────────────────────────");
  console.log("DataShield AI — Blockchain Audit Deployment");
  console.log("───────────────────────────────────────────────");
  console.log(`Deployer address : ${deployer.address}`);

  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log(`Deployer balance : ${hre.ethers.formatEther(balance)} ETH`);
  console.log("");

  // ── Deploy the contract ────────────────────────────────────────────────
  console.log("Deploying DataShieldAudit contract...");
  const DataShieldAudit = await hre.ethers.getContractFactory("DataShieldAudit");
  const contract = await DataShieldAudit.deploy();
  await contract.waitForDeployment();

  const deployedAddress = await contract.getAddress();
  console.log(`✅  DataShieldAudit deployed at: ${deployedAddress}`);

  // ── Persist the deployed address ───────────────────────────────────────
  const blockchainDir = path.resolve(__dirname, "..");
  const deploymentPath = path.join(blockchainDir, "deployment.json");

  const deploymentData = {
    contract: "DataShieldAudit",
    address: deployedAddress,
    network: hre.network.name,
    chainId: (await hre.ethers.provider.getNetwork()).chainId.toString(),
    deployer: deployer.address,
    timestamp: new Date().toISOString(),
  };

  fs.writeFileSync(deploymentPath, JSON.stringify(deploymentData, null, 2));
  console.log(`📄  Deployment info saved to: ${deploymentPath}`);

  // ── Persist the ABI ────────────────────────────────────────────────────
  const abiPath = path.join(blockchainDir, "abi.json");

  // Read the full artifact generated by Hardhat compilation
  const artifactPath = path.join(
    blockchainDir,
    "artifacts",
    "contracts",
    "DataShieldAudit.sol",
    "DataShieldAudit.json"
  );

  if (fs.existsSync(artifactPath)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
    fs.writeFileSync(abiPath, JSON.stringify(artifact.abi, null, 2));
    console.log(`📄  ABI saved to: ${abiPath}`);
  } else {
    console.warn("⚠️   Artifact not found — ABI file was not created.");
    console.warn(`     Expected at: ${artifactPath}`);
  }

  console.log("");
  console.log("───────────────────────────────────────────────");
  console.log("Deployment complete.");
  console.log("───────────────────────────────────────────────");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Deployment failed:", error);
    process.exit(1);
  });
